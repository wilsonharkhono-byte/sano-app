#!/usr/bin/env node
/**
 * Builds prototype.html — a single self-contained file for easy local review.
 * Inlines styles.css, script.js, and every referenced SVG asset as a data URI.
 *
 * Run:  node tools/build-prototype.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (f) => readFileSync(join(ROOT, f), 'utf8');

const toDataUri = (path) =>
  'data:image/svg+xml;base64,' +
  Buffer.from(readFileSync(join(ROOT, path))).toString('base64');

let html = read('index.html');
const css = read('styles.css');
const js = read('script.js');

// inline stylesheet + script — replacer functions so "$$" in the code is not
// interpreted as a String.replace substitution pattern
html = html.replace(/<link rel="stylesheet" href="styles.css">/, () => `<style>\n${css}\n</style>`);
html = html.replace(/<script src="script.js" defer><\/script>/, () => `<script defer>\n${js.replace(/<\/script>/g, '<\\/script>')}\n</script>`);
// preload of external asset no longer applies
html = html.replace(/\s*<link rel="preload" as="image" href="assets\/hero.svg">/, '');

// swap every assets/*.svg reference (in HTML and in the inlined JS) for a data URI
const assetRefs = new Set([...html.matchAll(/assets\/[\w\/.-]+\.svg/g)].map((m) => m[0]));
for (const ref of assetRefs) {
  html = html.split(ref).join(toDataUri(ref));
}

html = html.replace(
  '<title>',
  '<!-- Self-contained build generated by tools/build-prototype.mjs — do not edit by hand -->\n  <title>'
);

writeFileSync(join(ROOT, 'prototype.html'), html);
console.log(`prototype.html written (${(html.length / 1024).toFixed(0)} KB, ${assetRefs.size} assets inlined)`);
